package mekhq.campaign.universe.commandGeneration;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertTrue;

import megamek.common.enums.SkillLevel;
import mekhq.campaign.RandomOriginOptions;
import mekhq.campaign.personnel.enums.PersonnelRole;
import mekhq.campaign.universe.enums.ForceNamingMethod;
import org.junit.jupiter.api.Test;

/**
 * Constructor-default coverage for {@link CommandGenerationOptions}. The defaults must match the
 * legacy {@code RULESET_BASED} configuration of the deprecated {@code CompanyGenerationOptions}
 * this class replaced, so a fresh Command Designer run generates the same force it always did.
 */
class CommandGenerationOptionsTest {

    private static final PersonnelRole[] SUPPORT_ROLES = {
          PersonnelRole.MEK_TECH, PersonnelRole.MECHANIC, PersonnelRole.AERO_TEK, PersonnelRole.BA_TECH,
          PersonnelRole.DOCTOR, PersonnelRole.ADMINISTRATOR
    };

    @Test
    void constructor_seedsCoveragePercentsAtOneHundred_forEverySupportRole() {
        CommandGenerationOptions options = new CommandGenerationOptions();

        assertNotNull(options.getSupportPersonnelCoveragePercents());
        for (PersonnelRole role : SUPPORT_ROLES) {
            assertEquals(100, options.getSupportPersonnelCoveragePercents().get(role),
                  "Default coverage for " + role.name() + " should be 100");
        }
    }

    @Test
    void constructor_defaultsSkillLevelsToRandom_forEverySupportRole() {
        CommandGenerationOptions options = new CommandGenerationOptions();

        assertNotNull(options.getSupportPersonnelSkillLevels());
        for (PersonnelRole role : SUPPORT_ROLES) {
            // SkillLevel.NONE = the "Random" picker option: each generated person rolls their own level.
            assertEquals(SkillLevel.NONE, options.getSupportPersonnelSkillLevels().get(role),
                    "Default skill level for " + role.name() + " should be Random (SkillLevel.NONE)");
        }
    }

    @Test
    void constructor_assistantDefaults_matchLegacyPoolAssistantsBehavior() {
        CommandGenerationOptions options = new CommandGenerationOptions();

        assertTrue(options.isGenerateAstechs(), "Astechs generated by default");
        assertFalse(options.isAstechsAsPersonnel(), "Pool mode by default");
        assertEquals(SkillLevel.NONE, options.getAstechSkillLevel(), "Astech skill defaults to Random");

        assertTrue(options.isGenerateMedics());
        assertFalse(options.isMedicsAsPersonnel());
        assertEquals(SkillLevel.NONE, options.getMedicSkillLevel(), "Medic skill defaults to Random");
    }

    @Test
    void constructor_pipelineDefaults_matchLegacyRulesetBasedConfiguration() {
        CommandGenerationOptions options = new CommandGenerationOptions();

        // Rank assignment and personnel flags.
        assertTrue(options.isAutomaticallyAssignRanks());
        assertTrue(options.isAssignCompanyCommanderFlag());
        assertTrue(options.isAssignMekWarriorsCallSigns());
        assertTrue(options.isAssignFounderFlag());

        // Formation naming.
        assertEquals(ForceNamingMethod.ICAO_1956, options.getForceNamingMethod());
        assertTrue(options.isAlwaysNumberRegiments());

        // Formation icons.
        assertTrue(options.isGenerateFormationIcons());
        assertFalse(options.isUseSpecifiedFactionToGenerateFormationIcons());
        assertTrue(options.isGenerateOriginNodeFormationIcon());
        assertFalse(options.isUseOriginNodeFormationIconLogo());

        // Finances: the command is granted free, with working capital defaulting to six months of its running
        // costs, floored so it can pay its first month's wages.
        assertTrue(options.isProcessFinances());
        assertEquals(6, options.getStartingCashMonths());
        assertFalse(options.isRandomizeStartingCash());
        assertEquals(18, options.getRandomStartingCashDiceCount());
        assertEquals(10_000_000L, options.getMinimumStartingFloat());
        assertFalse(options.isStartingLoan());
        assertFalse(options.isPayForSetup());
    }

    /**
     * The recommended defaults from issue #9955. These are the values a player gets without touching
     * the dialog, so they are pinned rather than left to drift.
     */
    @Test
    void constructor_officerAndSimulationDefaults_matchTheRecommendedValues() {
        CommandGenerationOptions options = new CommandGenerationOptions();

        // The command is led by its best people rather than whoever the roll happened to seat first.
        assertTrue(options.isAssignBestCompanyCommander());
        assertTrue(options.isAssignBestOfficers());
        assertTrue(options.isAssignMostSkilledToPrimaryLances());
        assertTrue(options.isGenerateCaptains());

        // A medical reserve so the command can absorb casualties from its first contract.
        assertTrue(options.isGenerateMedicalReserve());

        // The starting simulation is opt-in; its sub-options stay on so turning it on gives the command a history.
        assertFalse(options.isRunStartingSimulation());
        assertEquals(10, options.getSimulationDuration());
        assertTrue(options.isSimulateRandomMarriages());
        assertTrue(options.isSimulateRandomProcreation());
    }

    @Test
    void constructor_randomOriginDefaults_randomizeEveryoneWithTheExtraPlanetaryOrigin() {
        RandomOriginOptions origin = new CommandGenerationOptions().getRandomOriginOptions();

        assertNotNull(origin);
        assertTrue(origin.isRandomizeOrigin());
        assertTrue(origin.isRandomizeDependentOrigin());
        assertFalse(origin.isRandomizeAroundSpecifiedPlanet());
        assertEquals(0, origin.getOriginSearchRadius());
        assertEquals(0.6, origin.getOriginDistanceScale(), 0.0001);
        assertFalse(origin.isAllowClanOrigins());
        assertTrue(origin.isExtraRandomOrigin());
    }

    @Test
    void forceDescriptorSnapshot_isLazilyInitialized_andNeverNull() {
        CommandGenerationOptions options = new CommandGenerationOptions();

        assertNotNull(options.getForceDescriptorSnapshot(), "Snapshot must lazy-initialize");
        assertSame(options.getForceDescriptorSnapshot(), options.getForceDescriptorSnapshot(),
              "Repeated access must return the same snapshot instance");
    }
    /** The dialog compares the tabs against the settings captured at Generate, so equality must be by value. */
    @Test
    void twoFreshOptionsAreEqual() {
        assertEquals(new CommandGenerationOptions(), new CommandGenerationOptions());
        assertEquals(new CommandGenerationOptions().hashCode(), new CommandGenerationOptions().hashCode());
    }

    @Test
    void aChangedSettingBreaksEquality() {
        CommandGenerationOptions options = new CommandGenerationOptions();
        CommandGenerationOptions changed = new CommandGenerationOptions();
        changed.setGenerateCaptains(!options.isGenerateCaptains());
        assertNotEquals(options, changed, "an officer toggle is part of the settings");

        changed = new CommandGenerationOptions();
        changed.getSupportPersonnelCoveragePercents().put(PersonnelRole.DOCTOR, 200);
        assertNotEquals(options, changed, "a coverage percentage is part of the settings");

        changed = new CommandGenerationOptions();
        changed.getForceDescriptorSnapshot().setYear(3025);
        assertNotEquals(options, changed, "the force description is part of the settings");

        changed = new CommandGenerationOptions();
        changed.getRandomOriginOptions().setOriginSearchRadius(250);
        assertNotEquals(options, changed, "the Random Origin choices are part of the settings");
    }
}
